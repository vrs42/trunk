// DESCRIPTION:
//   The Controller implements a timing generator and a large (huge!) block
// of purely combinatorial control logic, which together direct the operation
// of the registers and functional units in the DataPaths section.  The timing
// generator is, of course, a state machine that uses the current state and
// the opcode to determine the next state.  In the PDP-8/V, as it is in the 8/A
// and 8/E as well, the total number of states is fairly limited - there's only
// about a dozen.
//
//   The control block is simply a large mass of "random" logic that takes the
// current state and the current instruction, as well as some external flags
// and inputs, and generates the control signals for the DataPaths.  This is
// essentially just a giant PLA and could, and probably would in real hardware,
// be implemented as a ROM.  But here we simply write out all the equations and
// conditions and let the synthesis tool figure out a way to minimize it.
//
//   And by the way, there's a very nice chart available from Spare Time Gizmos
// that shows all the states in the PDP-8/V along with the associated operations
// for each of the major instruction groups. It's really a lot easier to under-
// stand how all this works if you have one of those handy!
//
