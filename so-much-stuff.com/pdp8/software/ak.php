<BODY><FONT size=4>
This is an archive of the Ax-yyyy software titles.
<P>
Since the files are organized by DEC part number, a 
word about part numbers is probably in order.  A DEC part number
might look like any of these:
        dec-812-pb
        dec-08-d01a-pb
        dec-08-d01a-b-pb
        ac-6527d-ma
depending on the vintage of the title in question.
<P>
The part numbers in this directory have the form Ax-yyyyv-lc, where 
<UL>
<LI>
x     is a document type (C for write-ups, K for papertape, etc.)
<LI>
yyyy  is the identifier for for the product
<LI>
v     is the revision identifier
<LI>
l     is the license type (B for binary, M for no license required, etc.)
<LI>
c     is the CPU (A for PDP-8, P for PDP-12, etc.)
</UL>
<P>
In these directories, Ax is stripped off, and the file type is 
indicate by a suffix (-pb, etc.) or an extension (.pdf, etc.).
This causes related files to be grouped together by yyyyv.
<P>
Often an additional code is present of the form AJyyyr0, which 
refers to the older naming scheme.  Thus c658d-ma is a new name 
for revision "d" of ajrla, which is the RL8A Diskless Controller 
test.
