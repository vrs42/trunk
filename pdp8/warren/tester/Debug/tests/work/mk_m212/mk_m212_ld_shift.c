/************************************************************************/
/*  mk_m212_ld_shift.c	generate test for PDP-8 card tester				*/
/*                      M212 6-bit l-r shift register					*/
/*                      load and shift tests							*/
/*  compile with Microsoft C 1.52 with command line:					*/
/*		cl /W4 mk_m212_ld_shift.c										*/
/*                                                                      */
/************************************************************************/

#define VERSION_STRING  "version 1.0  September 13, 2015"


#include <ctype.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define NUM_BITS       6
#define NUM_VALUES     (1 << NUM_BITS)

#define COL_IN_A_N     2
#define COL_ENABLE_A   8
#define COL_IN_B_N     9
#define COL_ENABLE_B  15
#define COL_RIGHT_IN  16
#define COL_ENABLE_R  17
#define COL_LEFT_IN   18
#define COL_ENABLE_L  19
#define COL_CLOCK     20
#define COL_FF0       21


unsigned int gray[NUM_VALUES + 1];

#define MAX_COL  80
int out_array[MAX_COL];		/* array of characters. NOT a string	*/


void init_gray( void )
{
    int				i;

	int				bit;
	unsigned int	mask;
	int				flag_store_ones;

	int				zeroes;
    int				ones;
    int				count;

	int				last_value;


    for (i = 0; i < (NUM_VALUES) + 1; i++) gray[i] = 0;

    for (bit = 0; bit < NUM_BITS; bit++)
    {
		mask = (1 << bit);
		zeroes = mask;
		ones   = mask << 1;
		count			= zeroes;
		flag_store_ones = 0;

		for (i = 0; i < NUM_VALUES; i++)
		{
			if (flag_store_ones) gray[i] |= mask;
			count--;
			if (count == 0)
			{
				flag_store_ones = 1 - flag_store_ones;
				count = ones;
			}
		}
	}

	/* check the gray codes */

	if (gray[0] != 0)
	{
		fprintf( stderr, "BROKEN graycode generation!\r\n" );
		fprintf( stderr, "   gray[0] != 0!\r\n" );
		exit( 1 );		
	}
	if (gray[NUM_VALUES] != 0)
	{
		fprintf( stderr, "BROKEN graycode generation!\r\n" );
		fprintf( stderr, "   gray[%d] != 0!\r\n", NUM_VALUES );
		exit( 1 );		
	}


	last_value = gray[NUM_VALUES - 1];
	for (i = 0; i < (NUM_VALUES + 1); i++)
	{
		count = 0;
		for (bit = 0; bit < NUM_BITS; bit++)
		{
			mask = (1 << bit);
			if ((gray[i] & mask) != (last_value & mask)) count++;
		}
		if (count != 1)
		{
			fprintf( stderr, "BROKEN graycode generation!\r\n" );
			fprintf( stderr, "i = %d\r\n", i );
			fprintf( stderr, "last    = %2u %02o\r\n", i, last_value, last_value );
			fprintf( stderr, "gray[i] = %2u %02o\r\n", i, gray[i], gray[i] );
			exit( 1 );
		}
		last_value = gray[i];
	}
}



void init_out_array( void )
{
	int		i;

	for (i = 0; i < MAX_COL; i++) out_array[i] = ' ';
}



void store_out_array( unsigned int column, int character )
{
    if ((column > 0) && (column <= MAX_COL)) out_array[column - 1] = character;
}


void store_binary_out_array( unsigned int column, unsigned int binary_code, int bits )
{
	int				i;
	unsigned int	mask;


	for (i = 0; i < bits; i++)
	{
		mask = 1 << (bits - 1 - i);
		store_out_array( column + i, (binary_code & mask) ? '1' : '0' );
	}
}


void store_ff_out_array( unsigned int column, unsigned int ff_value, int bits )
{
	int				i;
	unsigned int	mask;


	for (i = 0; i < bits; i++)
	{
		mask = 1 << (bits - 1 - i);
		store_out_array( column, (ff_value & mask) ? '1' : '0' );
		column++;
		store_out_array( column, (ff_value & mask) ? '0' : '1' );
		column++;
	}
}



void print_out_array( void )
{
	int		i;
	int		last_column;

	
	last_column = 0;
	for (i = 0; i < MAX_COL; i++)
	{
		if (out_array[i] != ' ') last_column = i;
	}
	for (i = 0; i <= last_column; i++)
	{
		printf( "%c", out_array[i] );
	}
	printf( "\r\n" );

	init_out_array();		/* get ready for next line	*/
}



void main( int argc )
{
    unsigned int    i;
	unsigned int	expected;


	/* process arguments		*/

	#define NUM_ARGS		1


	if (argc != NUM_ARGS)
	{
		fprintf( stderr, "mk_m212_ld_shift   make PDP-8 tester test for M212\r\n" );
		fprintf( stderr, "%s\r\n", VERSION_STRING );
		fprintf( stderr, "usage:  mk_m212_ld_shift\r\n" );
		fprintf( stderr, "   prints on stdout\r\n" );
		exit( 1 );
	}

	/* done processing arguments	*/	
	
	
	
	init_gray();
	init_out_array();

	
	printf( "; FOLLOWING SECTION IS GENERATED BY A PROGRAM\r\n" );
	printf( ";    see  mk_m212_ld_shift.c\r\n" );
	printf( "\r\n" );
	printf( "\r\n" );
	printf( "; TEST A INPUTS, GRAY CODE PATTERN\r\n" );
	printf( "\r\n" );
	printf( "; ENABLE A INPUTS\r\n" );
    store_out_array( COL_ENABLE_A, '1' );
	print_out_array();

	printf( "; LOAD FFs FROM INPUT A\r\n" );
	printf( "\r\n" );
	for (i = 1; i < (NUM_VALUES + 1); i++)	/* end with 00000 */
	{
		
		store_binary_out_array( COL_IN_A_N, gray[i], NUM_BITS );
		print_out_array();

		store_out_array( COL_CLOCK, '1' );
		store_ff_out_array( COL_FF0, gray[i], NUM_BITS );
		print_out_array();

		store_out_array( COL_CLOCK, '0' );
		print_out_array();
	}
	printf( "\r\n" );
	printf( "; DISABLE A INPUTS\r\n" );
    store_out_array( COL_ENABLE_A, '0' );
	print_out_array();

	printf( "\r\n" );
	printf( "\r\n" );
	printf( "; TEST B INPUTS\r\n" );
	printf( "\r\n" );
	printf( "; ENABLE B INPUTS\r\n" );
    store_out_array( COL_ENABLE_B, '1' );
	print_out_array();

	printf( "; LOAD FFs FROM INPUT B\r\n" );
	printf( "\r\n" );
	for (i = 1; i < (NUM_VALUES + 1); i++)	/* end with 00000 */
	{
		store_binary_out_array( COL_IN_B_N, gray[i], NUM_BITS );
		print_out_array();

		store_out_array( COL_CLOCK, '1' );
		store_ff_out_array( COL_FF0, gray[i], NUM_BITS );
		print_out_array();

		store_out_array( COL_CLOCK, '0' );
		print_out_array();
	}
	printf( "\r\n" );
	printf( "; DISABLE B INPUTS\r\n" );
    store_out_array( COL_ENABLE_B, '0' );
	print_out_array();



	printf( "\r\n" );
	printf( "\r\n" );
	printf( "; TEST SHIFT R (LOAD VIA A INPUTS)\r\n" );
	printf( "\r\n" );
	printf( "; SHIFT IN A ZERO\r\n" );
    store_out_array( COL_RIGHT_IN, '0' );
	print_out_array();

	printf( "; ENABLE A INPUTS, LOAD A, DISABLE A INPUTS\r\n" );
	printf( "; ENABLE SHIFT RIGHT, SHIFT, DISABLE SHIFT RIGHT\r\n" );
	for (i = 1; i < (NUM_VALUES + 1); i++)	/* end with 00000 */
	{
		store_out_array( COL_ENABLE_A, '1' );
		store_binary_out_array( COL_IN_A_N, gray[i], NUM_BITS );
		print_out_array();

		store_out_array( COL_CLOCK, '1' );
		store_ff_out_array( COL_FF0, gray[i], NUM_BITS );
		print_out_array();

		store_out_array( COL_CLOCK, '0' );
		store_out_array( COL_ENABLE_A, '0' );
		store_out_array( COL_ENABLE_R, '1' );
		print_out_array();
		
		expected = gray[i] >> 1;

		store_out_array( COL_CLOCK, '1' );
		store_ff_out_array( COL_FF0, expected, NUM_BITS );
		print_out_array();

		store_out_array( COL_CLOCK, '0' );
		store_out_array( COL_ENABLE_R, '0' );
		print_out_array();
	}


	printf( "\r\n" );
	printf( "\r\n" );
	printf( "; TEST SHIFT R (LOAD VIA A INPUTS)\r\n" );
	printf( "\r\n" );
	printf( "; SHIFT IN A ONE\r\n" );
    store_out_array( COL_RIGHT_IN, '1' );
	print_out_array();

	printf( "; ENABLE A INPUTS, LOAD A, DISABLE A INPUTS\r\n" );
	printf( "; ENABLE SHIFT RIGHT, SHIFT, DISABLE SHIFT RIGHT\r\n" );
	for (i = 1; i < (NUM_VALUES + 1); i++)	/* end with 00000 */
	{
		store_out_array( COL_ENABLE_A, '1' );
		store_binary_out_array( COL_IN_A_N, gray[i], NUM_BITS );
		print_out_array();

		store_out_array( COL_CLOCK, '1' );
		store_ff_out_array( COL_FF0, gray[i], NUM_BITS );
		print_out_array();

		store_out_array( COL_CLOCK, '0' );
		store_out_array( COL_ENABLE_A, '0' );
		store_out_array( COL_ENABLE_R, '1' );
		print_out_array();
		
		expected = (gray[i] >> 1) | (1 << (NUM_BITS - 1));

		store_out_array( COL_CLOCK, '1' );
		store_ff_out_array( COL_FF0, expected, NUM_BITS );
		print_out_array();

		store_out_array( COL_CLOCK, '0' );
		store_out_array( COL_ENABLE_R, '0' );
		print_out_array();
	}


	printf( "\r\n" );
	printf( "\r\n" );
	printf( "; TEST SHIFT L (LOAD VIA A INPUTS)\r\n" );
	printf( "\r\n" );
	printf( "; SHIFT IN A ZERO\r\n" );
    store_out_array( COL_LEFT_IN, '0' );
	print_out_array();

	printf( "; ENABLE A INPUTS, LOAD A, DISABLE A INPUTS\r\n" );
	printf( "; ENABLE SHIFT LEFT, SHIFT, DISABLE SHIFT LEFT\r\n" );
	for (i = 1; i < (NUM_VALUES + 1); i++)	/* end with 00000 */
	{
		store_out_array( COL_ENABLE_A, '1' );
		store_binary_out_array( COL_IN_A_N, gray[i], NUM_BITS );
		print_out_array();

		store_out_array( COL_CLOCK, '1' );
		store_ff_out_array( COL_FF0, gray[i], NUM_BITS );
		print_out_array();

		store_out_array( COL_CLOCK, '0' );
		store_out_array( COL_ENABLE_A, '0' );
		store_out_array( COL_ENABLE_L, '1' );
		print_out_array();
		
		expected = (gray[i] << 1) & (NUM_VALUES - 1);

		store_out_array( COL_CLOCK, '1' );
		store_ff_out_array( COL_FF0, expected, NUM_BITS );
		print_out_array();

		store_out_array( COL_CLOCK, '0' );
		store_out_array( COL_ENABLE_L, '0' );
		print_out_array();
	}


	printf( "\r\n" );
	printf( "\r\n" );
	printf( "; TEST SHIFT L (LOAD VIA A INPUTS)\r\n" );
	printf( "\r\n" );
	printf( "; SHIFT IN A ONE\r\n" );
    store_out_array( COL_LEFT_IN, '1' );
	print_out_array();

	printf( "; ENABLE A INPUTS, LOAD A, DISABLE A INPUTS\r\n" );
	printf( "; ENABLE SHIFT LEFT, SHIFT, DISABLE SHIFT LEFT\r\n" );
	for (i = 1; i < (NUM_VALUES + 1); i++)	/* end with 00000 */
	{
		store_out_array( COL_ENABLE_A, '1' );
		store_binary_out_array( COL_IN_A_N, gray[i], NUM_BITS );
		print_out_array();

		store_out_array( COL_CLOCK, '1' );
		store_ff_out_array( COL_FF0, gray[i], NUM_BITS );
		print_out_array();

		store_out_array( COL_CLOCK, '0' );
		store_out_array( COL_ENABLE_A, '0' );
		store_out_array( COL_ENABLE_L, '1' );
		print_out_array();
		
		expected = (gray[i] << 1) & (NUM_VALUES - 1) | 1;

		store_out_array( COL_CLOCK, '1' );
		store_ff_out_array( COL_FF0, expected, NUM_BITS );
		print_out_array();

		store_out_array( COL_CLOCK, '0' );
		store_out_array( COL_ENABLE_L, '0' );
		print_out_array();
	}


	printf( "\r\n" );
	printf( "\r\n" );
	printf( "; end of SECTION GENERATED BY A PROGRAM\r\n" );
	printf( "\r\n" );
	printf( "\r\n" );

}
